"""
Prediction utilities for the AI Health Risk Predictor project.

Loads a trained model pipeline and its metadata for a given disease, and
provides a single function to turn raw user input into a complete,
UI-ready prediction result (risk category, probability, risk level,
contributing factors).
"""

import json

import joblib
import pandas as pd

import config


def load_model_and_metadata(model_path: str, metadata_path: str):
    """
    Load a trained pipeline (.pkl) and its accompanying metadata (.json).

    Raises a clear, catchable error if either file is missing, so app.py
    can show a friendly message instead of crashing with a raw traceback.
    """
    try:
        pipeline = joblib.load(model_path)
    except FileNotFoundError:
        raise FileNotFoundError(
            f"Model file not found at {model_path}. "
            f"Run 'python train_models.py' first to generate it."
        )

    try:
        with open(metadata_path, "r") as f:
            metadata = json.load(f)
    except FileNotFoundError:
        raise FileNotFoundError(
            f"Metadata file not found at {metadata_path}. "
            f"Run 'python train_models.py' first to generate it."
        )

    return pipeline, metadata


def probability_to_risk_level(probability: float) -> str:
    """
    Convert a model's predicted probability (of the positive/disease class)
    into a human-readable risk category, using thresholds defined in
    config.py.
    """
    if probability < config.RISK_THRESHOLDS["low_max"]:
        return "Low"
    elif probability < config.RISK_THRESHOLDS["moderate_max"]:
        return "Moderate"
    else:
        return "High"


def get_top_contributing_factors(
    input_dict: dict, feature_importance: dict, top_n: int = 3
) -> list:
    """
    Identify which of the user's submitted values correspond to the
    model's most influential features overall, to show as "contributing
    factors" on the Result page.

    This uses the model's GLOBAL feature importance (from training) as
    a proxy explanation -- it does NOT compute a per-prediction, per-user
    explanation (that would require a library like SHAP, which we are
    intentionally not using to keep the project's dependencies minimal
    and free). This is clearly labeled as "model feature importance" in
    the UI, not as a medical or causal explanation specific to this user.

    Parameters
    ----------
    input_dict : dict
        The user's submitted feature values.
    feature_importance : dict
        Feature name -> importance score, from the saved metadata,
        already sorted descending by importance.
    top_n : int
        How many top factors to return.

    Returns
    -------
    list of dicts: [{"feature": ..., "value": ..., "importance": ...}, ...]
    """
    if not feature_importance:
        return []

    top_features = list(feature_importance.items())[:top_n]

    factors = []
    for feature_name, importance_score in top_features:
        factors.append({
            "feature": feature_name,
            "value": input_dict.get(feature_name),
            "importance": importance_score,
        })

    return factors


def predict_diabetes_risk(input_dict: dict) -> dict:
    """
    Run a full diabetes risk prediction for one set of user-submitted
    values.

    Parameters
    ----------
    input_dict : dict
        Must contain all keys listed in config.DIABETES_FEATURE_COLUMNS.

    Returns
    -------
    dict with keys: risk_label, probability, risk_level, top_factors,
    model_name, disclaimer
    """
    pipeline, metadata = load_model_and_metadata(
        config.DIABETES_MODEL_PATH, config.DIABETES_METADATA_PATH
    )

    # Build a single-row DataFrame with columns in the EXACT order used
    # during training. Using a DataFrame (not a raw list/array) means
    # scikit-learn matches by column name internally where possible, and
    # keeps the code readable and less error-prone than positional lists.
    feature_columns = config.DIABETES_FEATURE_COLUMNS
    input_row = pd.DataFrame([[input_dict[col] for col in feature_columns]],
                              columns=feature_columns)

    probability = float(pipeline.predict_proba(input_row)[0][1])
    predicted_class = int(pipeline.predict(input_row)[0])

    risk_level = probability_to_risk_level(probability)
    top_factors = get_top_contributing_factors(
        input_dict, metadata["feature_importance"], top_n=3
    )

    return {
        "risk_label": "High Risk" if predicted_class == 1 else "Low Risk",
        "probability": round(probability * 100, 1),
        "risk_level": risk_level,
        "top_factors": top_factors,
        "model_name": metadata["best_model_name"],
        "disclaimer": (
            "This is an educational risk estimate generated by a machine "
            "learning model, not a medical diagnosis. Consult a qualified "
            "healthcare professional for medical advice."
        ),
    }


